# Decode the 6.x reference 0x39 (legend/profile) and 0x34 packets.
KEY = bytes.fromhex('4E65786F6E496E632E')  # "NexonInc."

def crypt(body, inc):
    o = bytearray(body)
    for i in range(len(o)):
        grp = (i // 9) & 0xFF   # the group counter is a BYTE on both sides (client: cmp inc, bl)
        o[i] ^= KEY[i % 9]
        o[i] ^= grp
        if grp != inc:
            o[i] ^= inc
    return bytes(o)

def dump(label, raw):
    b = raw
    op, inc, body = b[3], b[4], b[5:]
    dec = crypt(body, inc)
    print(f'=== {label}: op=0x{op:02x} inc=0x{inc:02x} len={b[2]} bodylen={len(body)} ===')
    print(' hex  :', dec.hex(' '))
    print(' dec  :', ' '.join(str(x) for x in dec))
    print(' ascii:', ''.join(chr(x) if 32 <= x < 127 else '.' for x in dec))
    print()
    return dec

